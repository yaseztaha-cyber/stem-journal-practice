// Volume 3: +60 for G11 S1 (2026–2027). source='practice' ALWAYS.
// Transfer items pair TWO LOs (cross-subject synthesis), each code canonical.
type Difficulty = 'easy' | 'medium' | 'hard';
interface Comp { key: string; label: string; keywords: string[] }
export interface PackQ3 {
  category: Category;
  question_text: string;
  what_testing: string;
  difficulty: Difficulty;
  required_components: Comp[];
  source: 'practice';
  source_label: string;
  tags: string[];
  scope: {
    grade: number | null; semester: number | null; school_year: string;
    question_number: number | null; question_slot: number | null;
    question_type: string; learning_objectives: string[];
  };
}

const LBL = 'Practice · G11 S1';
const SY = '2026–2027';
function sc(slot: number, type: string, jn: number | null, los?: string[]): { grade: number | null; semester: number | null; school_year: string; question_number: number | null; question_slot: number | null; question_type: string; learning_objectives: string[] };
function sc(grade: number, semester: number | null, slot: number, type: string, jn: number | null, los?: string[]): { grade: number | null; semester: number | null; school_year: string; question_number: number | null; question_slot: number | null; question_type: string; learning_objectives: string[] };
function sc(...args: any[]) {
  // 3-arg form defaults to G11 S1; 5/6-arg form sets grade/semester explicitly.
  const [grade, semester, slot, type, jn, los] = args.length <= 4 ? [11, 1, args[0], args[1], args[2], args[3] ?? []] : [args[0], args[1], args[2], args[3], args[4], args[5] ?? []];
  return { grade, semester, school_year: SY, question_number: jn, question_slot: slot, question_type: type, learning_objectives: los };
}
function C(key: string, label: string, keywords: string[]): Comp { return { key, label, keywords }; }

